import assert from 'node:assert/strict';
import * as T from '../public/vendor/three.module.js';
import {SurfaceStream,TERRAIN_ANIMATIONS} from '../public/surface-streaming.js';
import {SurfaceCollisions} from '../public/surface-collision.js';

const body={id:'Earth',name:'Earth',solid:true,type:'PLANET'};
const pos=new T.Vector3(0,4,0), scene=new T.Scene(), session={body};
const stream=new SurfaceStream({scene,session});
const collision=new SurfaceCollisions(session);
const camera=new T.PerspectiveCamera(60,16/9,.15,6000);
const point=(x,y,z)=>{
 camera.position.copy(pos);camera.lookAt(pos.x+x,pos.y+y,pos.z+z);
 camera.updateMatrixWorld();
};
const frame=(dt=1/60)=>stream.update(pos,'High',{camera,mobile:true,dt});
const visible=()=>[...stream.chunks.values()].filter(g=>g.visible);
assert.deepEqual(stream.animations,TERRAIN_ANIMATIONS);
point(0,-.2,-1);frame();
assert(stream.chunks.size<=1,'mobile detail generation is bounded per frame');
assert(stream.distant.mesh&&stream.distant.mesh.visible,'the horizon fallback is available on the first frame');
const loading=visible().find(g=>g.position.y>0);
assert(loading&&loading.children[0].material.opacity<1,'loading and fade animate simultaneously');
const collisionAt=stream.collisionRevision;
const originalBoxes=stream.collisionBoxes;
for(let i=0;i<60;i++)frame();
assert(visible().every(g=>g.position.y===0&&g.children[0].material.opacity===1));
const first=new Set(visible());
point(0,-.2,1);frame();
assert([...first].some(g=>!g.visible),'turning off camera stops drawing immediately');
assert.equal(stream.collisionRevision,collisionAt);
assert.deepEqual(stream.collisionBoxes,originalBoxes);
assert(collision.query(-60,-60,60,60).size>0);
point(0,-.2,-1);frame();
assert(visible().some(g=>first.has(g)&&g.position.y>0),'returning reuses geometry and replays its entrance');
stream.setAnimation('loading',false);frame();
assert(visible().every(g=>g.position.y===0));
assert(visible().some(g=>g.children[0].material.opacity<1),'disabling motion keeps fading enabled');
for(const option of ['fade','trees'])stream.setAnimation(option,false);
frame();
assert(visible().every(g=>g.children[0].material.opacity===1));
for(let i=0;i<96;i++){
 const turn=i*Math.PI/13;
 point(Math.sin(turn),i%2?-1.6:-.2,Math.cos(turn));frame();
 assert(visible().every(g=>stream.inView(g.userData.cx,g.userData.cz,0)));
 assert(stream.chunks.size<=61,'moving through the view retains a bounded inactive cache');
}
const oldHorizon=stream.distant.mesh.geometry;
pos.set(4800,240,-12000);point(0,-3,-1);frame();
assert.equal(stream.distant.mesh.geometry,oldHorizon,'mobile horizon sampling keeps the old mesh during a cell change');
for(let i=0;i<16;i++)frame();
assert.notEqual(stream.distant.mesh.geometry,oldHorizon,'the rebuilt horizon eventually replaces the old mesh');
assert(stream.distant.mesh.visible,'flight and rapid motion keep a low-detail surface');
assert(visible().every(g=>!g.userData.props?.visible),'nearby detail is not drawn from high altitude');
const spruce={id:'spruce',x:0,y:0,z:-130};
const testMesh=()=>{
 const geometry=new T.BufferGeometry();
 geometry.setAttribute('position',new T.Float32BufferAttribute([0,0,-130,0,1,-130,1,0,-130],3));
 const mesh=new T.Mesh(geometry,new T.MeshBasicMaterial());
 return stream.scenerySegments(mesh,[{tree:spruce,start:0,end:3}]);
};
const lod={nearTrees:testMesh(),billboards:testMesh(),appear:1};
pos.set(0,4,0);point(0,0,-1);frame();
stream.setAnimation('trees',true);
stream.updateTreeLOD(lod,pos,true,1/60);
assert(lod.billboards.visible&&!lod.nearTrees.visible);
pos.z=-80;point(0,0,-1);frame();stream.updateTreeLOD(lod,pos,true,1/60);
assert(lod.billboards.visible&&lod.nearTrees.visible);
assert(lod.nearTrees.geometry.attributes.lodBlend.array[0]<1,'approach crossfades meshes');
pos.z=-30;point(0,0,-1);frame();stream.updateTreeLOD(lod,pos,true,1/60);
assert(lod.nearTrees.visible,'tree stays 3D inside the hysteresis band');
pos.z=0;point(0,0,-1);frame();stream.updateTreeLOD(lod,pos,true,1/60);
assert(lod.billboards.visible&&!lod.nearTrees.visible,'moving away switches instantly');
point(0,0,1);frame();stream.updateTreeLOD(lod,pos,true,1/60);
assert(!lod.billboards.visible&&!lod.nearTrees.visible,'offscreen instances submit no triangles');
stream.clear();
assert.equal(scene.children.length,1);
assert.equal(stream.collisionBoxes.length,0);
console.log('PASS limited terrain generation, frustum bounds, immediate culling, replay, independent transitions, stable collision and rapid movement fallback.');
