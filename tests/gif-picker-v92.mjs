import assert from 'node:assert/strict';
import {parseHTML} from 'linkedom';
import {gifGallery} from '../public/gif-gallery.js';
const {document}=parseHTML('<html><body></body></html>');globalThis.document=document;
const originalFetch=globalThis.fetch;
const remote={url:'https://nekos.best/api/v2/wave/test.gif'};
globalThis.fetch=async url=>String(url).includes('?')?{ok:true,json:async()=>({results:[remote]})}:Promise.reject(new TypeError('Failed to fetch'));
const chosen=[];const root=gifGallery({onChoose:file=>chosen.push(file)});document.body.append(root);
await root.search('');
await root.querySelector('.gifGrid button').onclick();assert.equal(chosen.length,1);
const online=root.querySelector('.gifCategories').lastElementChild;
online.onclick();await new Promise(resolve=>setTimeout(resolve,0));
await root.querySelector('.gifGrid button').onclick();
assert.match(root.querySelector('.gifGalleryStatus').textContent,/Online GIF download failed/);
assert.equal(root.querySelectorAll('.gifGrid button').length,24);
assert.equal(chosen.length,1,'failed remote choice must never silently send a different GIF');
await root.querySelector('.gifGrid button').onclick();assert.equal(chosen.length,2);
online.onclick();await new Promise(resolve=>setTimeout(resolve,0));
root.querySelector('.gifGrid img').onerror();await new Promise(resolve=>setTimeout(resolve,0));
assert.match(root.querySelector('.gifGalleryStatus').textContent,/images are unavailable/);
assert.equal(root.querySelectorAll('.gifGrid button').length,24);
root.dispose();globalThis.fetch=originalFetch;
console.log('PASS: blocked online downloads and previews recover to selectable game GIFs without sending a substitute.');
