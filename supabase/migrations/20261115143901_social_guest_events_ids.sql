CREATE FUNCTION public.tzg_guest_chat_send(p_visitor uuid,p_body text,p_mutation uuid) RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path='' AS $$
DECLARE guest tzg_private.guest_identities;body text:=tzg_private.clean_text(p_body);mid bigint;
BEGIN
 IF p_visitor IS NULL OR p_mutation IS NULL OR body IS NULL OR length(body)<1 OR length(body)>200 THEN RAISE EXCEPTION 'Enter a message with 1–200 characters.';END IF;
 PERFORM pg_advisory_xact_lock(951027001);
 SELECT * INTO guest FROM tzg_private.guest_identities WHERE visitor=p_visitor FOR UPDATE;
 IF NOT FOUND THEN RAISE EXCEPTION 'Choose a guest display name first.';END IF;
 SELECT id INTO mid FROM tzg_private.chat_messages WHERE guest_visitor=p_visitor AND mutation=p_mutation;
 IF FOUND THEN RETURN jsonb_build_object('id',mid::text);END IF;
 IF guest.last_message>now()-interval '3 seconds' OR (guest.window_start>now()-interval '1 minute' AND guest.message_count>=10) THEN RAISE EXCEPTION 'Wait a moment before sending again.';END IF;
 UPDATE tzg_private.guest_identities SET last_message=now(),window_start=CASE WHEN window_start<=now()-interval '1 minute' THEN now() ELSE window_start END,message_count=CASE WHEN window_start<=now()-interval '1 minute' THEN 1 ELSE message_count+1 END WHERE visitor=p_visitor;
 INSERT INTO tzg_private.chat_messages(username,display_name,body,mutation,guest_visitor) VALUES('guest',guest.display_name,body,p_mutation,p_visitor) RETURNING id INTO mid;
 PERFORM tzg_private.cleanup_temporary_chat();
 RETURN jsonb_build_object('id',mid::text);
END;$$;
REVOKE ALL ON FUNCTION public.tzg_guest_chat_send(uuid,text,uuid) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.tzg_guest_chat_send(uuid,text,uuid) TO anon,authenticated;
CREATE OR REPLACE FUNCTION tzg_private.cleanup_temporary_chat()
 RETURNS void
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
begin
 if not pg_try_advisory_xact_lock(951027001) then return;end if;
 delete from tzg_private.chat_messages where created_at<now()-interval '5 hours' OR id IN (SELECT id FROM tzg_private.chat_messages ORDER BY id DESC OFFSET 10);
 delete from tzg_private.social_messages where created_at<now()-interval '5 hours' or (deleted and updated_at<now()-interval '1 minute');
 delete from tzg_private.chat_reports where created_at<now()-interval '7 days';
 delete from tzg_private.message_change_limits where window_start<now()-interval '1 day';
 delete from tzg_private.chat_limits where window_start<now()-interval '1 day';
end;$function$
;
CREATE OR REPLACE FUNCTION public.tzg_chat_read(p_after bigint DEFAULT 0, p_ids bigint[] DEFAULT '{}'::bigint[])
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
declare caller uuid:=tzg_private.require_player();result jsonb;
begin perform tzg_private.cleanup_temporary_chat();
 if coalesce(array_length(p_ids,1),0)>100 then raise exception 'Too many message IDs.';end if; if p_after is null or p_after<0 then raise exception 'Invalid chat cursor.';end if;
 select coalesce(jsonb_agg(jsonb_build_object('guest',m.guest_visitor IS NOT NULL,'verified',m.verified,'deleted',m.deleted,'updated_at',m.updated_at,'id',m.id::text,'display_name',m.display_name,'avatar',m.avatar,'body',m.body,'created_at',m.created_at,'own',m.user_id=caller,'image_available',m.has_image,'name_color',(array['#ffb8b8','#9bd2ff','#b9f6af','#e4c1ff','#ffd68e','#99eee7','#ffb5dc','#e7ee98'])[1+abs(hashtextextended(m.username,0)%8)::integer]) order by m.id),'[]'::jsonb) into result from (
 select c.id,c.guest_visitor,c.user_id,c.deleted,c.updated_at,p.verified,coalesce(p.username,c.username) as username,coalesce(p.display_name,c.display_name) as display_name,p.avatar,c.body,c.created_at,exists(select 1 from tzg_private.chat_images i where i.message_id=c.id) as has_image from tzg_private.chat_messages c left join tzg_private.player_profiles p on p.user_id=c.user_id where not tzg_private.social_blocked(caller,c.user_id) order by c.id desc limit 10)m;
 return result;
end; $function$
;
CREATE OR REPLACE FUNCTION public.tzg_guest_chat(p_after bigint DEFAULT 0)
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
declare result jsonb;begin
 perform tzg_private.cleanup_temporary_chat();
 if p_after is null or p_after<0 then raise invalid_parameter_value using message='Invalid cursor.';end if;
 select coalesce(jsonb_agg(jsonb_build_object('guest',m.guest_visitor IS NOT NULL,'id',m.id::text,'username',p.username,'display_name',coalesce(p.display_name,m.display_name),'avatar',p.avatar,'verified',coalesce(p.verified,false),'body',m.body,'created_at',m.created_at,'online',tzg_private.guest_online(p.user_id)) order by m.id),'[]'::jsonb) into result from (select * from tzg_private.chat_messages where not deleted and id>p_after order by id desc limit 10)m left join tzg_private.player_profiles p on p.user_id=m.user_id;
 return result;end;$function$
;

