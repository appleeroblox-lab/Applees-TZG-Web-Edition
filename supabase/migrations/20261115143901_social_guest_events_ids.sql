CREATE FUNCTION public.tzg_guest_identity(p_visitor uuid,p_name text) RETURNS void LANGUAGE plpgsql SECURITY DEFINER SET search_path='' AS $$
DECLARE name text:=tzg_private.clean_text(p_name);
BEGIN
 IF p_visitor IS NULL OR name IS NULL OR length(name)<2 OR length(name)>32 THEN RAISE EXCEPTION 'Use a display name with 2–32 characters.';END IF;
 INSERT INTO tzg_private.guest_identities(visitor,display_name) VALUES(p_visitor,name) ON CONFLICT(visitor) DO UPDATE SET display_name=excluded.display_name;
END;$$;
